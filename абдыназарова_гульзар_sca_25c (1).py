import math

eps = 1e-6
def f(x):
    return math.log(x) + x * x - 3.126
def df(x):
    return 1 / x + 2 * x


# 1. Дихотомия
a = 1.2
b = 2.1
steps = 0

while b - a >= eps:
    c = (a + b) / 2
    steps += 1

    if f(a) * f(c) <= 0:
        b = c
    else:
        a = c

x = (a + b) / 2

print("Дихотомия:")
print("x =", x)
print("шагов =", steps)
print("|f(x)| =", abs(f(x)))


# 2. Ньютон
x = 1.515
steps = 0

while True:
    xn = x - f(x) / df(x)
    steps += 1

    if abs(xn - x) < eps:
        break

    x = xn

print("\nНьютон:")
print("x =", xn)
print("шагов =", steps)
print("|f(x)| =", abs(f(xn)))


# 3. Метод хорд
a = 1.2
b = 2.1
old_x = None
steps = 0

while True:
    x = (a * f(b) - b * f(a)) / (f(b) - f(a))
    steps += 1

    if old_x is not None and abs(x - old_x) < eps:
        break

    if f(a) * f(x) <= 0:
        b = x
    else:
        a = x

    old_x = x

print("\nХорды:")
print("x =", x)
print("шагов =", steps)
print("|f(x)| =", abs(f(x)))


# 4. Золотое сечение
a = 1.2
b = 2.1
tau = (math.sqrt(5) - 1) / 2

def F(x):
    return f(x) ** 2

x1 = b - tau * (b - a)
x2 = a + tau * (b - a)

steps = 0

while b - a >= eps:
    if F(x1) < F(x2):
        b = x2
        x2 = x1
        x1 = b - tau * (b - a)
    else:
        a = x1
        x1 = x2
        x2 = a + tau * (b - a)

    steps += 1

x = (a + b) / 2

print("\nЗолотое сечение:")
print("x =", x)
print("шагов =", steps)
print("|f(x)| =", abs(f(x)))